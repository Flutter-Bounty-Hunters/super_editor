"""Generate pinned Unicode 16 tables. Pass directory containing the four input files.

Inputs: unicode.org/Public/16.0.0/ucd/{LineBreak.txt,UnicodeData.txt,
EastAsianWidth.txt,emoji/emoji-data.txt}. Names below are the local download names.
Unicode data license: UNICODE-LICENSE.txt. See README.md for reproduction.
"""
from pathlib import Path
import hashlib
import sys

root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1])
files = {name: source / f'Flow{name}-16.txt' for name in ['LineBreak', 'UnicodeData', 'EastAsianWidth', 'Emoji']}

expected = {
    'LineBreak': 'e97e4259d0d20fab150b9c7b4b28abfae5cd78ca97e7f4ac6ed20d685d5f4a7c',
    'UnicodeData': 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
    'EastAsianWidth': '43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b',
    'Emoji': 'f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a',
}
for name, path in files.items():
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected[name]:
        raise ValueError(f'{name}: input does not match the pinned Unicode 16 data')

def records(path):
    for line in path.read_text().splitlines():
        value = line.split('#')[0].strip()
        if not value: continue
        field, prop, *_ = [x.strip() for x in value.split(';')]
        ends = field.split('..')
        yield int(ends[0], 16), int(ends[-1], 16), prop

classes = sorted({prop for _, _, prop in records(files['LineBreak'])} | {'XX'})
values = [classes.index('XX') | 512] * 0x110000
# UCD special defaults for unassigned code points; explicit records override.
for a,b,c in [(0x3400,0x4dbf,'ID'),(0x4e00,0x9fff,'ID'),(0xf900,0xfaff,'ID'),
              (0x20000,0x2fffd,'ID'),(0x30000,0x3fffd,'ID'),(0x1f000,0x1faff,'ID'),
              (0x1fc00,0x1fffd,'ID'),(0x20a0,0x20cf,'PR')]:
    for i in range(a,b+1): values[i] = classes.index(c) | 512
for a,b,prop in records(files['LineBreak']):
    for i in range(a,b+1): values[i] = (values[i] & ~63) | classes.index(prop)
first = None
for line in files['UnicodeData'].read_text().splitlines():
    fields = line.split(';')
    cp, name, category = int(fields[0],16), fields[1], fields[2]
    if name.endswith(', First>'): first = cp; continue
    start = first if name.endswith(', Last>') else cp
    first = None
    flags = (64 if category in ('Mn','Mc') else 0) | (128 if category=='Pi' else 0) | (256 if category=='Pf' else 0)
    for i in range(start,cp+1): values[i] = (values[i] & ~512) | flags
for a,b,prop in records(files['EastAsianWidth']):
    if prop in ('F','W','H'):
        for i in range(a,b+1): values[i] |= 1024
for a,b,prop in records(files['Emoji']):
    if prop == 'Extended_Pictographic':
        for i in range(a,b+1): values[i] |= 2048
rows=[]
start=0
for i in range(1,len(values)+1):
    if i == len(values) or values[i] != values[start]:
        rows.append(f'  0x{start:X},\n  0x{i-1:X},\n  {values[start]},')
        start=i
output = root / 'lib/src/experimental/flow/unicode/line_break_data.dart'
output.write_text('// GENERATED by tool/unicode/generate_line_break_data.py; Unicode 16.0.0.\n'
    '// Unicode data license: tool/unicode/UNICODE-LICENSE.txt.\n'
    '// Low 6 bits: line class; flags: mark=64, Pi=128, Pf=256, Cn=512, EastAsian=1024, EP=2048.\n'
    "part of '../flow.dart';\n\n"
    + 'enum _Lb {\n  ' + ',\n  '.join((c.lower() + '_' if c in ('AS','IS','IN') else c.lower()) for c in classes) + '\n}\n\n'
    + 'const _lineBreakData = <int>[\n' + '\n'.join(rows) + '\n];\n')
for name,path in files.items(): print(name,hashlib.sha256(path.read_bytes()).hexdigest())
print(len(rows),'ranges;',output.stat().st_size,'bytes')
